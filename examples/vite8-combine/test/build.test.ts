import { spawn } from 'node:child_process';
import { existsSync, readFileSync, rmSync, utimesSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { describe, expect, it } from 'vitest';

import { runBuild, runScript } from '../../shared/example-testkit';

const root = join(__dirname, '..');

/**
 * watch / build 子进程的输出会混入 ANSI 颜色码和 watch TUI 重定向时灌入的 NUL，
 * 两者都必须剥掉才能得到可断言的纯文本。ESC 用 String.fromCharCode(27) 拼出，
 * 避免正则字面量里出现控制符触发 no-control-regex（同 example-testkit 的套路）。
 */
const ANSI_SGR = new RegExp(`${String.fromCharCode(27)}\\[[0-9;]*m`, 'g');

function scrub(text: string): string {
  return text.replace(ANSI_SGR, '').split(String.fromCharCode(0)).join('');
}

async function build(n: number) {
  const { code, stdout } = await runBuild(root, 'build', n);
  if (code !== 0) {
    throw new Error(`build:${n} failed (code=${code})\n${stdout}`);
  }
}

function read(...segments: string[]): string {
  return readFileSync(join(root, ...segments), 'utf-8');
}

function targetPath(n: number): string {
  return join(root, `src/combine.${n}.ts`);
}


describe('vite-plugin-combine example configs', () => {
  /*
   * exports 策略 — 组合代码的导出形态。
   * 每条都做双向断言：目标形态必须出现、另一种形态必须不出现，
   * 避免"产物里出现名字就算过"的假阳性。
   */
  describe('exports 策略', () => {
    it('named: 只产出具名 re-export，不带 default', async () => {
      await build(1);
      const code = read('dist/1/combine.1.js');

      // 每个源文件先被引入，再以具名形式再导出。
      expect(code).toMatch(/import isAsyncFunction from ['"]\.\/isAsyncFunction\.js/);
      expect(code).toMatch(/export \{[^}]*isAsyncFunction[^}]*\}/);
      // named 策略不产出 default（双向断言）。
      expect(code).not.toContain('as default');
    }, 60000);

    it('default: 只产出 default 对象，不带具名 re-export', async () => {
      await build(2);
      const code = read('dist/2/combine.2.js');

      // 完整形态：default 对象由 target 名派生（combine_2_default），导出为 default。
      expect(code).toMatch(/\bcombine_2_default as default\b/);
      // default 策略不产出具名 re-export：export 块里不得出现任何裸导出名。
      expect(code).not.toMatch(/export \{[^}]*\bisAsyncFunction\b/);
    }, 60000);

    it('both: 同时产出具名 re-export 与 default 对象', async () => {
      await build(3);
      const code = read('dist/3/combine.3.js');

      // 完整形态：同一个 export 块里既有 default 对象，也有裸的具名导出。
      expect(code).toMatch(/\bcombine_3_default as default\b/);
      expect(code).toMatch(/export \{[^}]*\bisAsyncFunction\b[^}]*\}/);
    }, 60000);

    it('none: 只做副作用导入，导出为空', async () => {
      await build(6);
      const code = read('dist/6/combine.6.js');

      expect(code).toMatch(/^import "\.\//m);
      // none 策略的产物里不该有任何 export 语句（实测连 `export {}` 都没有）。
      // 旧写法 not.toMatch(/export \{ is/) 只排除以 is 开头的导出名，
      // 换个文件名的组件就会漏判。
      expect(code).not.toMatch(/^export\b/m);

      // 入口声明同样只剩空导出。
      const dts = read('dist/6/combine.6.d.ts');
      expect(dts).toContain('export {};');
      expect(dts).not.toContain('isAsyncFunction');
    }, 60000);
  });

  /*
   * nameExport — 导出名的生成规则。
   */
  describe('nameExport', () => {
    it('true: 以文件名的驼峰形式作为导出名', async () => {
      await build(1);
      const code = read('dist/1/combine.1.js');

      // 关键证据：format_date.ts 必须变成 formatDate。
      // 其它源文件名本身就是驼峰，nameExport 失效时它们照样通过，
      // 只有下划线文件名能区分「转换生效」和「根本没转换」。
      expect(code).toMatch(/export \{[^}]*\bformatDate\b[^}]*\}/);
      // 原始下划线名不得作为**导出名**出现（import 路径里出现是正常的）。
      expect(code).not.toMatch(/export \{[^}]*\bformat_date\b/);

      // 已是驼峰的文件名保持不变（转换不能破坏原名）。
      expect(code).toMatch(/export \{[^}]*isAsyncFunction[^}]*\}/);
      expect(code).toMatch(/export \{[^}]*isDate[^}]*\}/);
    }, 60000);

    it('函数: 按自定义规则改写导出名', async () => {
      await build(4);
      const code = read('dist/4/combine.4.js');

      // 一条断言锁定完整形态：本地名仍是 isAsyncFunction，导出名被改成 myIsAsyncFunction。
      // 拆成「as myIsAsyncFunction」+「not as isAsyncFunction」会漏掉
      // `export { isAsyncFunction }`（无别名）这种未改名形态，断言因此形同虚设。
      expect(code).toMatch(/\bisAsyncFunction as myIsAsyncFunction\b/);

      const dts = read('dist/4/combine.4.d.ts');
      expect(dts).toContain('myIsAsyncFunction');
    }, 60000);
  });

  /*
   * beforeWrite — 组合代码写盘前的最后一次改写。
   */
  describe('beforeWrite', () => {
    it('banner 写进入口并一路保留到最终产物', async () => {
      await build(5);
      const code = read('dist/5/combine.5.js');

      // beforeWrite 返回的 banner 必须在产物里：证明它确实参与了写盘前的改写，
      // 而不是写完就被后续流程覆盖掉。
      expect(code).toContain('Auto-generated by vite-plugin-combine');
      // 组合入口只做 import/export 转发，绝不能把源文件实现内联进来。
      // [object AsyncFunction] 是 isAsyncFunction.ts 的函数体特征。
      expect(code).not.toContain('[object AsyncFunction]');
    }, 60000);
  });

  /*
   * dts — 声明产物的布局与形态。
   *
   * 布局由 vite-plugin-dts 的 entryRoot 推断决定：include 里同时有
   * src/util/*.ts 与 src/combine.N.ts，公共父目录是 src/，因此声明保留 util/ 层级。
   */
  describe('dts 产物', () => {
    it('源文件声明保留 util/ 层级，入口声明用相对说明符引用', async () => {
      await build(1);

      // 源文件声明必须真的生成了内容（只断言文件存在测不出空文件）。
      const fnDts = read('dist/1/util/isAsyncFunction.d.ts');
      expect(fnDts).toContain('export default function isAsyncFunction');
      expect(read('dist/1/util/noop.d.ts')).toContain('declare function noop');

      const dts = read('dist/1/combine.1.d.ts');
      expect(dts).toContain('./util/isAsyncFunction');
      expect(dts).toMatch(/export \{ default as isAsyncFunction \}/);
    }, 60000);

    it('default 策略的入口声明产出 _default 变量', async () => {
      await build(2);
      const dts = read('dist/2/combine.2.d.ts');
      expect(dts).toContain('declare const _default');
    }, 60000);

    it('both 策略的入口声明同时含具名导出与 _default', async () => {
      await build(3);
      const dts = read('dist/3/combine.3.d.ts');
      expect(dts).toContain('declare const _default');
      expect(dts).toContain('isAsyncFunction');
    }, 60000);

    it('cjs 产物配套 .d.cts 声明（扩展名按产物配对）', async () => {
      await build(1);

      // 强断言前置：先验 cjs 产物内容，失败信息才指向内容而不是路径。
      // config 1 是 es + cjs 双格式：package.json 无 type 字段时产物是 .js / .cjs。
      expect(read('dist/1/combine.1.cjs')).toMatch(/exports\./);

      // 声明必须与产物配对：.d.cts 与 .d.ts 内容完全一致，
      // 只断言文件存在的话，产出一个空 .d.cts 也会通过。
      const dts = read('dist/1/combine.1.d.ts');
      const dcts = read('dist/1/combine.1.d.cts');
      expect(dcts).toBe(dts);
      expect(dcts).toContain('isAsyncFunction');
    }, 60000);
  });

  /*
   * target 生命周期 — 它是构建期产物，不是用户文件。
   */
  describe('target 生命周期', () => {
    it('构建前不存在，构建结束后被清理', async () => {
      // 前置状态用 rmSync 确定性准备，不依赖前序用例是否清理干净
      // （watch 用例被 SIGKILL 时 finally 可能来不及执行）。
      rmSync(targetPath(1), { force: true });

      await build(1);

      // 真正的验证：closeBundle 必须删掉本次写入的组合入口。
      expect(existsSync(targetPath(1))).toBe(false);
    }, 60000);

    it('target 上已存在内容不同的文件时，拒绝覆盖并中断构建', async () => {
      const target = targetPath(1);
      const userContent = 'export const mine = 1;\n';
      writeFileSync(target, userContent);

      try {
        const { code, stdout } = await runBuild(root, 'build', 1);

        // 插件无法确认该文件来源，宁可失败也不覆盖用户代码。
        expect(code).not.toBe(0);
        expect(stdout).toContain('already exists');
        // 用户文件必须原样保留。
        expect(readFileSync(target, 'utf-8')).toBe(userContent);
      }
      finally {
        rmSync(target, { force: true });
      }
    }, 60000);

    it('watch 模式下 target 跨轮保留（否则下一轮 entry 缺失）', async () => {
      const proc = spawn('pnpm', ['run', 'build:1:watch'], {
        cwd: root,
        detached: true,
        env: { ...process.env, FORCE_COLOR: '0' },
        stdio: ['ignore', 'pipe', 'pipe']
      });
      let text = '';
      proc.stdout?.on('data', (buf: Buffer) => {
        text = scrub(text + buf.toString('utf-8'));
      });
      proc.stderr?.on('data', (buf: Buffer) => {
        text = scrub(text + buf.toString('utf-8'));
      });
      const kill = () => {
        try {
          if (proc.pid != null) {
            process.kill(-proc.pid, 'SIGKILL');
          }
        }
        catch {
          proc.kill('SIGKILL');
        }
      };
      const waitFor = async (pred: () => boolean, label: string, ms = 120000) => {
        const t0 = Date.now();
        while (!pred()) {
          if (Date.now() - t0 > ms) {
            kill();
            throw new Error(`watch: ${label} timed out\n${text}`);
          }
          await new Promise((res) => {
            setTimeout(res, 100);
          });
        }
      };
      try {
        await waitFor(() => /built in/.test(text), 'first build');
        expect(existsSync(targetPath(1))).toBe(true);
        expect(text).not.toContain('already exists');

        // touch 一个源文件触发重建；重建必须成功且 target 仍在。
        const now = new Date();
        utimesSync(join(root, 'src/util/noop.ts'), now, now);
        const countBuilds = () => (text.match(/built in/g) ?? []).length;
        const before = countBuilds();
        await waitFor(() => countBuilds() > before, 'rebuild after touch');

        expect(text).not.toContain('UNRESOLVED_ENTRY');
        expect(existsSync(targetPath(1))).toBe(true);
      }
      finally {
        kill();
        rmSync(targetPath(1), { force: true });
      }
    }, 240000);
  });

  /*
   * 并发 — 两个配置同时构建，各自的 target 与产物互不干扰。
   */
  describe('并发', () => {
    it('同一包目录并行构建两个配置互不冲突', async () => {
      const [r1, r2] = await Promise.all([
        runBuild(root, 'build', 1),
        runBuild(root, 'build', 2)
      ]);

      expect(r1.code).toBe(0);
      expect(r2.code).toBe(0);
      expect(read('dist/1/combine.1.js')).toMatch(/export \{[^}]*isAsyncFunction/);
      expect(read('dist/2/combine.2.js')).toContain('as default');
      // 两个 target 都已被清理。
      expect(existsSync(targetPath(1))).toBe(false);
      expect(existsSync(targetPath(2))).toBe(false);
    }, 120000);
  });

  /*
   * dev — 组合入口在 dev server 下同样可用。
   */
  describe('dev', () => {
    it('dev server 以 target 路径提供组合入口，说明符可被直接取到', async () => {
      const handle = await runScript(root, 'dev', 1);
      try {
        const res = await fetch(`${handle.baseUrl}/src/combine.1.ts`);
        expect(res.ok).toBe(true);

        const code = await res.text();
        // 具名导出指向源文件；dev 下说明符被解析成带扩展名的 root URL。
        expect(code).toMatch(
          /export \{ default as isAsyncFunction \} from ['"]\/src\/util\/isAsyncFunction\.ts/
        );

        // 说明符必须能被 dev 服务直接取到（真实消费链路验证）。
        const dep = await fetch(`${handle.baseUrl}/src/util/isAsyncFunction.ts`);
        expect(dep.ok).toBe(true);
      }
      finally {
        await handle.close();
      }
    }, 60000);
  });
});
